/**
 * 角色配置（单一真相源）
 *
 * 所有角色相关的资源（Live2D 模型、背景、人设、问候语、音色样本等）
 * 都集中定义在这里。账号密码登录时决定加载哪个角色。
 *
 * 新增角色只需在 CHARACTERS 数组里加一项，无需改其他代码。
 *
 * 共享配置（不随角色变）：
 * - LLM API Key / 模型 / endpoint
 * - TTS 引擎和阿里云 API Key
 * - UI 配色、窗口缩放
 * - TTS 一键克隆标记
 *
 * 角色独立（每个角色各一份）：
 * - 账号 / 密码
 * - Live2D 模型路径
 * - 背景 / 登录图 / BGM / Logo
 * - 人设（system prompt）
 * - 问候语
 * - 音色样本（克隆用）
 * - 聊天会话 / 记忆（按 characterId 隔离存储）
 */

export interface Character {
  /** 角色 ID（用于 localStorage 隔离，不可改） */
  id: string;
  /** 显示名 */
  name: string;
  /** 登录账号 */
  account: string;
  /** 登录密码 */
  password: string;
  /** Live2D 模型路径（相对 /public） */
  live2dPath: string;
  /** 聊天界面背景图 */
  bgImage: string;
  /** 登录界面背景图 */
  bgLoginImage: string;
  /** BGM 音频文件 */
  bgm: string;
  /** 顶部 Logo 精灵图 */
  spriteLogo: string;
  /** 音色样本（用于一键克隆） */
  voiceSample: string;
  /** 人设（system prompt） */
  personality: string;
  /** 首次进入的随机问候语 */
  greetings: string[];
  /**
   * 按时段的开场白（可选）。命中时段就用这里的候选随机挑一条，否则用 greetings。
   * 区间是 [from, to) 的小时数；to < from 表示跨午夜（如 23 → 5）。
   *
   * 真由理用它：五条开场白都是**原声整句**（见 lib/catchphrase.ts），
   * 语义按时段配（早上说おはよう、晚上说おかえり），避免"半夜说早上好"。
   */
  timedGreetings?: Array<{ from: number; to: number; greetings: string[] }>;
}

