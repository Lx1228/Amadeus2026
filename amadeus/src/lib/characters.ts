/** 随机取一条问候语（配了 timedGreetings 的角色按时段挑） */
export function getRandomGreeting(characterId: string): string {
  const c = getCharacterById(characterId);

  if (c.timedGreetings && c.timedGreetings.length > 0) {
    const h = new Date().getHours();
    // 区间 [from, to)；to < from 表示跨午夜（23 点 → 5 点）
    const slot = c.timedGreetings.find((s) =>
      s.from <= s.to ? h >= s.from && h < s.to : h >= s.from || h < s.to
    );
    const pool = slot ? slot.greetings : c.greetings;
    if (pool.length > 0) return pool[Math.floor(Math.random() * pool.length)];
  }

  const greetings = c.greetings;
  return greetings[Math.floor(Math.random() * greetings.length)];
}
